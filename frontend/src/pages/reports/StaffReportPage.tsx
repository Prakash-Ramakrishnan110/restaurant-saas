import React, { useState, useEffect, useCallback, useMemo } from "react";
import { Users, Receipt, TrendingUp, RefreshCw, Award } from "lucide-react";
import { apiClient } from "../../api/client";
import { formatRupees } from "../../utils/currency";
import { Button } from "../../components/ui/button";

interface StaffMetric {
  user_id: string;
  full_name: string;
  role: string;
  settled_count: number;
  total_sales_paise: number;
  average_ticket_paise: number;
}

interface StaffReportData {
  start_date: string;
  end_date: string;
  staff: StaffMetric[];
}

export const StaffReportPage: React.FC = () => {
  const [data, setData] = useState<StaffReportData | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [datePreset, setDatePreset] = useState<"TODAY" | "7D" | "30D">("7D");

  const fetchStaffReport = useCallback(async () => {
    setIsLoading(true);
    setError(null);

    const now = new Date();
    const endStr = now.toISOString().split("T")[0];
    let daysAgo = 6;
    if (datePreset === "TODAY") daysAgo = 0;
    if (datePreset === "30D") daysAgo = 29;

    const startDateObj = new Date(now.getTime() - daysAgo * 24 * 60 * 60 * 1000);
    const startStr = startDateObj.toISOString().split("T")[0];

    try {
      const res = await apiClient.get<StaffReportData>("/reports/staff/", {
        params: { start_date: startStr, end_date: endStr },
      });
      setData(res.data);
    } catch {
      setError("Failed to load staff performance report.");
    } finally {
      setIsLoading(false);
    }
  }, [datePreset]);

  useEffect(() => {
    fetchStaffReport();
  }, [fetchStaffReport]);

  const summary = useMemo(() => {
    if (!data || !data.staff) {
      return { totalSettled: 0, totalSalesPaise: 0, staffCount: 0 };
    }
    const staffCount = data.staff.length;
    const totalSettled = data.staff.reduce((acc, curr) => acc + curr.settled_count, 0);
    const totalSalesPaise = data.staff.reduce((acc, curr) => acc + curr.total_sales_paise, 0);
    return { staffCount, totalSettled, totalSalesPaise };
  }, [data]);

  return (
    <div className="p-6 max-w-7xl mx-auto space-y-6">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-foreground flex items-center gap-2">
            <Users className="w-6 h-6 text-[#FF6A00]" />
            Staff Performance &amp; Register Audit
          </h1>
          <p className="text-sm text-muted-foreground">
            Sales volume, bills settled, and average ticket size generated by each team member
            (H-22).
          </p>
        </div>
        <div className="flex items-center gap-2">
          <Button variant="outline" size="sm" onClick={fetchStaffReport} disabled={isLoading}>
            <RefreshCw className={`w-4 h-4 mr-2 ${isLoading ? "animate-spin" : ""}`} />
            Refresh
          </Button>
        </div>
      </div>

      {error && (
        <div className="p-4 bg-red-50 dark:bg-red-950/40 border border-red-200 dark:border-red-800 rounded-lg text-sm text-red-700 dark:text-red-300">
          {error}
        </div>
      )}

      {/* Date Preset Selector */}
      <div className="flex items-center gap-2">
        {(["TODAY", "7D", "30D"] as const).map((p) => (
          <button
            key={p}
            onClick={() => setDatePreset(p)}
            className={`px-3 py-1.5 text-xs font-semibold rounded-lg border transition-colors ${
              datePreset === p
                ? "bg-[#0B1F3B] text-white border-[#0B1F3B] dark:bg-white dark:text-[#0B1F3B]"
                : "bg-background text-muted-foreground border-border hover:bg-muted"
            }`}
          >
            {p === "TODAY" ? "Today" : p === "7D" ? "Last 7 Days" : "Last 30 Days"}
          </button>
        ))}
      </div>

      {/* KPI Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <div className="p-4 rounded-xl border border-border bg-card">
          <span className="text-xs font-semibold text-muted-foreground uppercase flex items-center gap-1.5">
            <Users className="w-4 h-4 text-blue-500" />
            Active Cashiers / Staff
          </span>
          <div className="text-2xl font-bold text-foreground mt-1">{summary.staffCount}</div>
        </div>

        <div className="p-4 rounded-xl border border-border bg-card">
          <span className="text-xs font-semibold text-muted-foreground uppercase flex items-center gap-1.5">
            <Receipt className="w-4 h-4 text-emerald-500" />
            Total Bills Settled
          </span>
          <div className="text-2xl font-bold text-foreground mt-1">{summary.totalSettled}</div>
        </div>

        <div className="p-4 rounded-xl border border-border bg-card">
          <span className="text-xs font-semibold text-muted-foreground uppercase flex items-center gap-1.5">
            <TrendingUp className="w-4 h-4 text-[#FF6A00]" />
            Gross Team Sales
          </span>
          <div className="text-2xl font-bold text-foreground mt-1">
            {formatRupees(summary.totalSalesPaise)}
          </div>
        </div>
      </div>

      {/* Staff Table */}
      <div className="border border-border rounded-xl overflow-hidden bg-card shadow-sm">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="bg-muted/50 border-b border-border text-xs uppercase text-muted-foreground font-semibold">
              <tr>
                <th className="px-4 py-3">Team Member</th>
                <th className="px-4 py-3">Role</th>
                <th className="px-4 py-3 text-right">Settled Invoices</th>
                <th className="px-4 py-3 text-right">Average Ticket</th>
                <th className="px-4 py-3 text-right">Total Sales</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-border/60">
              {isLoading ? (
                <tr>
                  <td colSpan={5} className="px-4 py-8 text-center text-muted-foreground">
                    Loading staff performance...
                  </td>
                </tr>
              ) : !data?.staff || data.staff.length === 0 ? (
                <tr>
                  <td colSpan={5} className="px-4 py-8 text-center text-muted-foreground">
                    No staff sales recorded for this date range.
                  </td>
                </tr>
              ) : (
                data.staff.map((s, idx) => (
                  <tr key={s.user_id} className="hover:bg-muted/30 transition-colors">
                    <td className="px-4 py-3 font-semibold text-foreground flex items-center gap-2">
                      {idx === 0 && <Award className="w-4 h-4 text-[#FF6A00]" />}
                      {s.full_name}
                    </td>
                    <td className="px-4 py-3">
                      <span className="px-2 py-0.5 text-xs font-semibold rounded bg-muted text-muted-foreground">
                        {s.role}
                      </span>
                    </td>
                    <td className="px-4 py-3 font-medium text-foreground text-right">
                      {s.settled_count}
                    </td>
                    <td className="px-4 py-3 font-medium text-muted-foreground text-right">
                      {formatRupees(s.average_ticket_paise)}
                    </td>
                    <td className="px-4 py-3 font-bold text-foreground text-right">
                      {formatRupees(s.total_sales_paise)}
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
