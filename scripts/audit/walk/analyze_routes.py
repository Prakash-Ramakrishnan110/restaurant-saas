"""Step 4: Route Inventory, Role URL Probe Merge, Data Source & Test Coverage Analyzer.

Reads:
- frontend/src/App.tsx
- frontend/src/StaffApp.tsx
- frontend/src/app/navigation.ts
- frontend/src/tests/* and frontend/e2e/*
- docs/audit/walk/raw/route_probe_raw.json (if generated by Playwright)

Writes:
- docs/audit/walk/routes.csv
- docs/audit/walk/raw/routes_analysis.json
"""

import csv
import json
import os
import re

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
APP_TSX = os.path.join(BASE_DIR, "frontend/src/App.tsx")
STAFF_APP_TSX = os.path.join(BASE_DIR, "frontend/src/StaffApp.tsx")
NAV_TS = os.path.join(BASE_DIR, "frontend/src/app/navigation.ts")
PAGES_DIR = os.path.join(BASE_DIR, "frontend/src/pages")
TESTS_DIR = os.path.join(BASE_DIR, "frontend/src/tests")
E2E_DIR = os.path.join(BASE_DIR, "frontend/e2e")
PROBE_JSON = os.path.join(BASE_DIR, "docs/audit/walk/raw/route_probe_raw.json")
OUT_CSV = os.path.join(BASE_DIR, "docs/audit/walk/routes.csv")
OUT_RAW = os.path.join(BASE_DIR, "docs/audit/walk/raw/routes_analysis.json")


def parse_routes_from_file(filepath: str, is_public_app: bool = False):
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    comp_files = {}
    # Match lazyNamed(() => import("./pages/..."), "CompName") including multiline
    for m in re.finditer(
        r'const\s+([A-Za-z0-9_]+)\s*=\s*lazyNamed\(\s*\(\)\s*=>\s*import\(["\']([^"\']+)["\']\),\s*["\']([^"\']+)["\']\s*\)',
        content,
    ):
        comp_files[m.group(1)] = m.group(2)
    # Match React.lazy(() => import("./pages/...").then(...))
    for m in re.finditer(
        r'const\s+([A-Za-z0-9_]+)\s*=\s*React\.lazy\(\s*\(\)\s*=>\s*import\(["\']([^"\']+)["\']\)',
        content,
    ):
        comp_files[m.group(1)] = m.group(2)

    routes = []
    # Match <Route path="..." element={...} /> across multiline
    for m in re.finditer(
        r'<Route\s+path=["\']([^"\']+)["\']\s+element=\{([\s\S]*?)\}\s*/>',
        content,
    ):
        path_str = m.group(1)
        el_str = m.group(2)
        if path_str == "*" and is_public_app:
            continue

        guard = "PUBLIC"
        perm = ""
        if "requirePlatformAdmin" in el_str:
            guard = "PLATFORM_ADMIN"
        elif "<ProtectedRoute" in el_str:
            pm = re.search(r'requiredPermission=["\']([^"\']+)["\']', el_str)
            if pm:
                perm = pm.group(1)
                guard = f"AUTHENTICATED (perm:{perm})"
            else:
                guard = "AUTHENTICATED"

        comps = re.findall(r"<([A-Z][A-Za-z0-9_]+)", el_str)
        inner = [c for c in comps if c not in ("ProtectedRoute", "Navigate", "React")]
        if "<Navigate" in el_str:
            to_m = re.search(r'to=["\']([^"\']+)["\']', el_str)
            comp_name = f"Redirect({to_m.group(1)})" if to_m else "Redirect"
        else:
            comp_name = inner[0] if inner else "Unknown"

        imp = comp_files.get(comp_name, "")
        resolved_file = ""
        if imp.startswith("./"):
            cand = os.path.normpath(os.path.join(BASE_DIR, "frontend/src", imp + ".tsx"))
            if os.path.exists(cand):
                resolved_file = os.path.relpath(cand, BASE_DIR).replace("\\", "/")

        routes.append(
            {
                "route": path_str,
                "component": comp_name,
                "component_file": resolved_file,
                "guard": guard,
                "required_permission": perm,
                "source_router": os.path.basename(filepath),
            }
        )
    return routes


def get_sidebar_paths():
    with open(NAV_TS, "r", encoding="utf-8") as f:
        nav_txt = f.read()
    return set(re.findall(r'path:\s*["\'](/[^"\']*)["\']', nav_txt))


def inspect_component(rel_path: str):
    if not rel_path:
        return "NONE", []
    full = os.path.join(BASE_DIR, rel_path)
    if not os.path.exists(full):
        return "NONE", []
    with open(full, "r", encoding="utf-8", errors="ignore") as f:
        txt = f.read()

    endpoints = set()
    for m in re.finditer(
        r'(?:apiClient|publicHttp)\.(get|post|patch|put|delete)(?:<[\s\S]{0,120}?>)?\(\s*[`\'"]([^`\'"]+)[`\'"]',
        txt,
    ):
        endpoints.add(f"{m.group(1).upper()} {m.group(2).split('?')[0]}")
    for m in re.finditer(r'(ordersApi|publicQrApi)\.([A-Za-z0-9_]+)\s*\(', txt):
        endpoints.add(f"{m.group(1)}.{m.group(2)}")

    if endpoints or "apiClient." in txt or "ordersApi." in txt or "publicQrApi." in txt:
        data_source = "API"
    elif "useState" in txt or "useReducer" in txt or "localStorage" in txt:
        data_source = "LOCAL"
    else:
        data_source = "NONE"
    return data_source, sorted(endpoints)


def find_test_coverage(route: str, component: str, test_dir: str):
    if not os.path.exists(test_dir):
        return []
    hits = []
    # Match either component name (except generic Redirect/RootRedirect) or non-trivial route
    comp_base = component.split("(")[0]
    route_clean = route.strip("/")
    for fname in sorted(os.listdir(test_dir)):
        if not fname.endswith((".ts", ".tsx")):
            continue
        fpath = os.path.join(test_dir, fname)
        with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
        matched = False
        if comp_base not in ("Unknown", "Redirect", "RootRedirect", "NotFoundPage"):
            if re.search(rf"\b{re.escape(comp_base)}\b", content):
                matched = True
        if not matched and route_clean and route not in ("/", "*", "/403"):
            if f'"{route}"' in content or f"'{route}'" in content or f"`{route}`" in content:
                matched = True
        if matched:
            hits.append(fname)
    return hits


def main():
    routes = parse_routes_from_file(APP_TSX, is_public_app=True) + parse_routes_from_file(
        STAFF_APP_TSX, is_public_app=False
    )
    # Deduplicate keeping first specific route (App.tsx /q/:token also listed in StaffApp.tsx)
    seen = set()
    unique_routes = []
    for r in routes:
        key = r["route"]
        if key in seen:
            continue
        seen.add(key)
        unique_routes.append(r)

    sidebar_paths = get_sidebar_paths()

    probe = {}
    if os.path.exists(PROBE_JSON):
        with open(PROBE_JSON, "r", encoding="utf-8") as f:
            probe = json.load(f)

    rows = []
    for r in unique_routes:
        route = r["route"]
        comp = r["component"]
        in_sidebar = "Y" if route in sidebar_paths else "N"
        data_source, endpoints = inspect_component(r["component_file"])
        unit_tests = find_test_coverage(route, comp, TESTS_DIR)
        e2e_tests = find_test_coverage(route, comp, E2E_DIR)
        covered = "Y" if (unit_tests or e2e_tests) else "N"

        p_entry = probe.get(route, {})
        allowed_roles = p_entry.get("allowed_roles", [])
        unauth_behaviors = p_entry.get("unauthorized_behaviors", [])

        # Normalize roles allowed by URL cleanly
        roles_str = "; ".join(allowed_roles) if allowed_roles else r["guard"]
        unauth_str = "; ".join(unauth_behaviors) if unauth_behaviors else "Not probed"

        is_alias_or_error = route in ("/", "*", "/403", "/suspended", "/login", "/change-password") or comp.startswith("Redirect(")
        is_dev = route.startswith("/dev/")
        url_only = "Y" if (in_sidebar == "N" and not is_alias_or_error and not is_dev) else "N"

        rows.append(
            {
                "route": route,
                "component": comp,
                "component_file": r["component_file"],
                "in_sidebar": in_sidebar,
                "url_only_reachable": url_only,
                "guard": r["guard"],
                "roles_allowed_by_url": roles_str,
                "unauthorized_behavior": unauth_str,
                "data_source": data_source,
                "api_endpoints": "; ".join(endpoints) if endpoints else "NONE",
                "unit_tests": "; ".join(unit_tests) if unit_tests else "NONE",
                "e2e_tests": "; ".join(e2e_tests) if e2e_tests else "NONE",
                "covered_by_tests": covered,
            }
        )

    os.makedirs(os.path.dirname(OUT_CSV), exist_ok=True)
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    with open(OUT_RAW, "w", encoding="utf-8") as f:
        json.dump(
            {
                "total_routes": len(rows),
                "in_sidebar_count": sum(1 for x in rows if x["in_sidebar"] == "Y"),
                "url_only_count": sum(1 for x in rows if x["url_only_reachable"] == "Y"),
                "covered_count": sum(1 for x in rows if x["covered_by_tests"] == "Y"),
                "routes": rows,
            },
            f,
            indent=2,
        )
    print(f"Wrote {OUT_CSV} ({len(rows)} routes).")


if __name__ == "__main__":
    main()
